"""Render manuscript drafts and evidence documents from the number registry.

Every number in the generated text comes from the registry (NUMBER_PROVENANCE_MDPI.csv). Templates use
{{TOKEN}} and {{CI:LO_TOKEN:HI_TOKEN}}; an unknown token stops the build.
"""
