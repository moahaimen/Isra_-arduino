TOKEN_RE = re.compile(r"\{\{(CI:)?([A-Za-z0-9_]+)(?::([A-Za-z0-9_]+))?\}\}")
USED_TOKENS: dict[str, set] = {}


def render(text: str, R: Registry, doc: str) -> str:
    used = USED_TOKENS.setdefault(doc, set())

    def sub(m):
        if m.group(1):
            lo, hi = m.group(2), m.group(3)
            for t in (lo, hi):
                if t not in R.entries:
                    raise KeyError(f"{doc}: unknown token {t}")
            used.update((lo, hi))
            return R.ci(lo, hi)
        t = m.group(2)
        if t not in R.entries:
            raise KeyError(f"{doc}: unknown token {t}")
        used.add(t)
        return R.v(t)

    out = TOKEN_RE.sub(sub, text)
    if "{{" in out:
        raise ValueError(f"{doc}: unrendered placeholder left")
    return out


# --------------------------------------------------------------------------------- helpers

def prov_row(R, tok, label):
    e = R.entries[tok]
    rnd = "no rounding" if e.decimals is None else f"{e.decimals} dp" + (", signed" if e.signed else "")
    return f"| {label} | {e.value} | `{tok}` | {e.status} | `{e.source_file}` | `{e.key}` | {e.calculation} | {rnd} |"


PROV_HEAD = ["| Quantity | Value | Token | Status | Source file | Key / row | Calculation | Rounding |",
             "|---|---|---|---|---|---|---|---|"]


def prov_table(R, rows):
    lines = list(PROV_HEAD)
    for tok, label in rows:
        if tok in R.entries:
            lines.append(prov_row(R, tok, label))
    return lines


def ci_text(R, base):
    lo, hi = f"{base}_LO", f"{base}_HI"
    if lo in R.entries and hi in R.entries:
        return f"{R.v(base)} {R.ci(lo, hi)}"
    return R.v(base)


