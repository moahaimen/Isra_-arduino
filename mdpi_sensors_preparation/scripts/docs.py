def build_all(R, caps, tabs, ff_rows, summary):
    MAN.mkdir(parents=True, exist_ok=True)
    USED_TOKENS.clear()
    rendered = {}
    for d in DRAFTS:
        txt = render((TPL / f"{d}.md.tmpl").read_text(), R, d)
        (MAN / f"{d}.md").write_text(txt)
        rendered[d] = txt
    first_cite = outline_and_order(R, caps, tabs)
    (OUT / "references.bib").write_text(BIB)
    (MAN / "references.bib").write_text(BIB)
    if hasattr(ff_rows, 'to_dict'):
        ff_rows = ff_rows.fillna('').to_dict('records')
    evidence_report(R, ff_rows, summary)
    literature_and_gap(R)
    claim_map(R)
    with open(MAN / "TOKENS_USED.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["draft", "token", "value", "status", "source_file", "key_or_row"])
        for d, toks in USED_TOKENS.items():
            for t in sorted(toks):
                e = R.entries[t]
                w.writerow([d, t, e.value, e.status, e.source_file, e.key])
    # compiled draft (Markdown + Word via pandoc when available)
    comp = "\n\n".join(rendered[d] for d in DRAFTS)
    comp += "\n\n# Figures\n\n" + (OUT / "figures/FIGURE_CAPTIONS.md").read_text()
    comp += "\n\n# Tables\n\n" + (OUT / "tables/ALL_TABLES.md").read_text()
    (MAN / "MANUSCRIPT_DRAFT_COMPILED.md").write_text(comp)
    try:
        subprocess.run(["pandoc", "-f", "markdown-yaml_metadata_block", str(MAN / "MANUSCRIPT_DRAFT_COMPILED.md"), "-o", str(MAN / "MANUSCRIPT_DRAFT_COMPILED.docx")],
                       check=True, capture_output=True, timeout=120)
    except Exception as exc:  # pandoc optional
        print("pandoc not available or failed:", exc)
    return rendered, first_cite


